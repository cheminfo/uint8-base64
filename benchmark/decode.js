import { Buffer } from 'node:buffer';

import Benchmark from 'benchmark';
import { XSadd } from 'ml-xsadd';

import { decode, encode } from '../src/index.ts';

const textDecoder = new TextDecoder();
const options = { minSamples: 30, maxTime: 5 };

for (const size of [512, 12288, 1048576, 16777216]) {
  const bytes = randomBytes(size, size);
  const base64 = encode(bytes);
  // The alternatives all take a string, so materializing one is part of their
  // cost: this package's contract is Uint8Array in, Uint8Array out.
  const asString = textDecoder.decode(base64);

  const reference = Buffer.from(asString, 'base64');
  const current = decode(base64);
  let identical = reference.length === current.length;
  for (let i = 0; identical && i < reference.length; i++) {
    if (reference[i] !== current[i]) identical = false;
  }

  console.log(
    `\n=== ${size} bytes (${base64.length} base64 bytes) | matches Buffer: ${identical} ===`,
  );

  new Benchmark.Suite()
    .add('decode', () => decode(base64), options)
    .add(
      'Buffer.from',
      () => Buffer.from(textDecoder.decode(base64), 'base64'),
      options,
    )
    .add(
      'Uint8Array.fromBase64',
      () => Uint8Array.fromBase64(textDecoder.decode(base64)),
      options,
    )
    .on('cycle', (event) => {
      const nsPerByte = 1e9 / event.target.hz / size;
      const mbPerSecond = (size * event.target.hz) / 1e6;
      console.log(
        `${String(event.target)} — ${nsPerByte.toFixed(4)} ns/byte, ${mbPerSecond.toFixed(0)} MB/s`,
      );
    })
    .run();
}

/**
 * Reproducible random bytes.
 * @param {number} length - number of bytes to generate.
 * @param {number} seed - seed for the generator.
 * @returns {Uint8Array} the generated bytes.
 */
function randomBytes(length, seed) {
  const generator = new XSadd(seed);
  const bytes = new Uint8Array(length);
  for (let i = 0; i < length; i += 4) {
    const value = generator.getUint32();
    bytes[i] = value;
    bytes[i + 1] = value >>> 8;
    bytes[i + 2] = value >>> 16;
    bytes[i + 3] = value >>> 24;
  }
  return bytes;
}
